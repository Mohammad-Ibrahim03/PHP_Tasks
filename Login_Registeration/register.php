<?php
require_once 'db.php';
$message = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $name = trim($_POST['name']);
    $email = trim($_POST['email']);
    $password = $_POST['password'];

    if (!empty($name) && !empty($email) && !empty($password)) {
        // Prevent duplicate user emails using prepared statements
        $stmt = $pdo->prepare("SELECT id FROM users WHERE email = ?");
        $stmt->execute([$email]);
        
        if ($stmt->rowCount() > 0) {
            $message = "Error: This email address is already registered.";
        } else {
            $hashedPassword = password_hash($password, PASSWORD_DEFAULT);
            $insertStmt = $pdo->prepare("INSERT INTO users (name, email, password) VALUES (?, ?, ?)");
            
            if ($insertStmt->execute([$name, $email, $hashedPassword])) {
                header("Location: login.php?registered=success");
                exit();
            } else {
                $message = "Registration failed. Please try again.";
            }
        }
    } else {
        $message = "All fields are required[cite: 3].";
    }
}
?>

